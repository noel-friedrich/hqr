const FONT_ASCENT = 5;
const FONT_HEIGHT = 6;

export function validateTomThumbText(text) {
  const unsupported = [...text].find((character) => {
    const codePoint = character.codePointAt(0);
    return !GLYPHS[codePoint];
  });
  if (unsupported) {
    throw new Error(
      `Tom Thumb cannot render ${JSON.stringify(unsupported)}. Use printable ASCII characters.`,
    );
  }
}

export function renderTomThumbLine(text) {
  validateTomThumbText(text);
  const width = Math.max(1, text.length * 4 - 1);
  const pixels = Array.from({ length: FONT_HEIGHT }, () =>
    Array(width).fill(false),
  );

  [...text].forEach((character, characterIndex) => {
    const [advance, glyphWidth, glyphHeight, xOffset, yOffset, rowText] =
      GLYPHS[character.codePointAt(0)];
    const rows = rowText.split(",");
    const top = FONT_ASCENT - yOffset - glyphHeight;
    const left = characterIndex * advance + xOffset;

    for (let row = 0; row < glyphHeight; row += 1) {
      const bits = Number.parseInt(rows[row], 16);
      for (let column = 0; column < glyphWidth; column += 1) {
        if ((bits & (0x80 >> column)) !== 0) {
          pixels[top + row][left + column] = true;
        }
      }
    }
  });

  return pixels;
}
